pub(super) const DESCRIPTION: &[&str] = &[
    "podrunner runs CI jobs. For each job it starts one fresh unit, runs the official runner once in it, and destroys the unit.",
    "serve takes jobs from the sources of a configuration file. run runs the jobs of one workflow file on this host, with no forge.",
];

